//! Project notes in the vault: a manual backup of the project records.
//!
//! The index is the only source of truth. `export` writes a generated note per project and
//! `import` restores records from those notes. Nothing reads the notes back automatically.

use std::path::PathBuf;

use anyhow::{bail, Context, Result};

use crate::store::{Project, ProjectDir, Store, Vault};

/// The folder inside a vault that holds the project notes.
pub const NOTES_DIR: &str = "Projects";

#[derive(Debug, PartialEq)]
pub struct ParsedProject {
    /// `id` and `vault_id` are not in the note: they are filled in on import.
    pub project: Project,
    pub vault_name: Option<String>,
}

#[derive(Debug, Default)]
pub struct ExportReport {
    /// Vault name and the note written.
    pub written: Vec<(String, PathBuf)>,
    /// Projects with no vault, which cannot be exported.
    pub skipped: Vec<String>,
}

#[derive(Debug, Default)]
pub struct ImportReport {
    pub added: Vec<String>,
    pub updated: Vec<String>,
    /// Existing projects left alone because `--overwrite` was not given.
    pub skipped: Vec<String>,
    pub warnings: Vec<String>,
}

/// The note for one project. The order is fixed so repeated exports produce identical files.
pub fn render_note(p: &Project, vault_name: Option<&str>) -> String {
    let mut out = format!(
        "# Project: {}\n\n> Generated by `knowledge-bae project export`. Change it with `knowledge-bae project edit`; `project import` restores it.\n\n",
        p.name
    );
    out.push_str(&format!("{DESCRIPTION}\n{}\n\n", p.description));
    out.push_str(&format!("{DETAILS}\n- Vault: {}\n", vault_name.unwrap_or("none")));
    out.push_str(&format!("- Project number: {}\n", p.project_number));
    for location in &p.vault_locations {
        out.push_str(&format!("- Location: {location}\n"));
    }
    out.push_str(&format!("\n{DIRECTORIES}\n"));
    for d in &p.dirs {
        out.push_str(&format!("- {}\n", d.path));
        if !d.origin.is_empty() {
            out.push_str(&format!("  - origin: {}\n", d.origin));
        }
    }
    out.push_str(&format!("\n{MISC}\n{}\n\n", p.misc));
    out.push_str(&format!("{SUMMARY}\n{}\n", p.summary_instructions));
    out
}

const DESCRIPTION: &str = "## Description";
const DETAILS: &str = "## Details";
const DIRECTORIES: &str = "## Directories";
const MISC: &str = "## Misc";
const SUMMARY: &str = "## Summary instructions";

/// Reads a note written by `render_note`. Only its own section headings split the text, so
/// other `## ` lines inside a description are kept.
pub fn parse_note(text: &str) -> Result<ParsedProject> {
    let mut lines = text.lines();
    let title = lines.by_ref().find(|l| !l.trim().is_empty()).unwrap_or_default();
    let name = title.strip_prefix("# Project: ").map(str::trim).filter(|n| !n.is_empty());
    let Some(name) = name else {
        bail!("not a project note (it should start with `# Project: <name>`)");
    };

    let mut sections: Vec<(&str, Vec<&str>)> = Vec::new();
    for line in lines {
        let heading = [DESCRIPTION, DETAILS, DIRECTORIES, MISC, SUMMARY].into_iter().find(|h| line.trim_end() == *h);
        match (heading, sections.last_mut()) {
            (Some(h), _) => sections.push((h, Vec::new())),
            (None, Some((_, body))) => body.push(line),
            (None, None) => {} // the generated banner
        }
    }
    let body = |heading: &str| -> String {
        let text = sections.iter().find(|(h, _)| *h == heading).map(|(_, b)| b.join("\n")).unwrap_or_default();
        text.trim_matches(|c| c == '\n' || c == '\r').to_string()
    };

    let mut p = Project {
        name: name.to_string(),
        description: body(DESCRIPTION),
        misc: body(MISC),
        summary_instructions: body(SUMMARY),
        ..Project::default()
    };
    let mut vault_name = None;
    for line in body(DETAILS).lines() {
        if let Some(v) = line.strip_prefix("- Vault: ") {
            vault_name = Some(v.trim().to_string()).filter(|v| v != "none" && !v.is_empty());
        } else if let Some(n) = line.strip_prefix("- Project number: ") {
            p.project_number = n.trim().to_string();
        } else if let Some(l) = line.strip_prefix("- Location: ") {
            p.vault_locations.push(l.to_string());
        }
    }
    for line in body(DIRECTORIES).lines() {
        if let Some(origin) = line.strip_prefix("  - origin: ") {
            if let Some(last) = p.dirs.last_mut() {
                last.origin = origin.trim().to_string();
            }
        } else if let Some(path) = line.strip_prefix("- ") {
            p.dirs.push(ProjectDir { path: path.to_string(), origin: String::new() });
        }
    }
    Ok(ParsedProject { project: p, vault_name })
}

/// The note's file name for a project: its name with characters that are not allowed in file names replaced.
pub fn note_file_name(name: &str) -> String {
    let safe: String = name.chars().map(|c| if "/\\:*?\"<>|".contains(c) { '-' } else { c }).collect();
    format!("{safe}.md")
}

/// Writes `<vault>/Projects/<name>.md` for every project linked to one of `vaults`.
pub fn export(store: &Store, vaults: &[Vault]) -> Result<ExportReport> {
    let projects = store.list_projects()?;
    let mut report = ExportReport {
        skipped: projects.iter().filter(|p| p.vault_id.is_none()).map(|p| p.name.clone()).collect(),
        ..ExportReport::default()
    };
    for vault in vaults {
        let folder = std::path::Path::new(&vault.path).join(NOTES_DIR);
        for p in projects.iter().filter(|p| p.vault_id == Some(vault.id)) {
            std::fs::create_dir_all(&folder).with_context(|| format!("creating {}", folder.display()))?;
            let file = folder.join(note_file_name(&p.name));
            let text = render_note(p, Some(&vault.name));
            // Leave an identical note alone so the vault's git history and Obsidian see no change.
            if std::fs::read_to_string(&file).ok().as_deref() != Some(text.as_str()) {
                std::fs::write(&file, text).with_context(|| format!("writing {}", file.display()))?;
            }
            report.written.push((vault.name.clone(), file));
        }
    }
    Ok(report)
}

/// Restores projects from the notes in `vaults`. Existing names are kept unless `overwrite`.
pub fn import(store: &mut Store, vaults: &[Vault], overwrite: bool) -> Result<ImportReport> {
    let mut report = ImportReport::default();
    for vault in vaults {
        let folder = std::path::Path::new(&vault.path).join(NOTES_DIR);
        if !folder.is_dir() {
            continue;
        }
        let mut files: Vec<PathBuf> = std::fs::read_dir(&folder)
            .with_context(|| format!("reading {}", folder.display()))?
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.extension().is_some_and(|x| x == "md"))
            .collect();
        files.sort();
        for file in files {
            let label = file.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
            let parsed = match std::fs::read_to_string(&file).map_err(anyhow::Error::from).and_then(|t| parse_note(&t)) {
                Ok(parsed) => parsed,
                Err(e) => {
                    report.warnings.push(format!("{label}: skipped ({e:#})"));
                    continue;
                }
            };
            let mut project = parsed.project;
            if let Some(vault_name) = &parsed.vault_name {
                match store.find_vault(vault_name)? {
                    Some(v) => project.vault_id = Some(v.id),
                    None => report.warnings.push(format!(
                        "'{}' names the vault '{vault_name}', which is not registered; imported without a vault",
                        project.name
                    )),
                }
            }
            let name = project.name.clone();
            let result = match store.find_project(&name)? {
                Some(_) if !overwrite => {
                    report.skipped.push(name);
                    continue;
                }
                Some(existing) => {
                    project.id = existing.id;
                    store.update_project(&project).map(|_| report.updated.push(name.clone()))
                }
                None => store.add_project(&project).map(|_| report.added.push(name.clone())),
            };
            if let Err(e) = result {
                report.warnings.push(format!("could not import '{name}': {e:#}"));
            }
        }
    }
    Ok(report)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> Project {
        Project {
            name: "Billing API".into(),
            description: "Handles invoices.\n\n## Other\nStill the description.".into(),
            vault_locations: vec!["work/billing".into(), "notes/Billing; extras".into()],
            project_number: "P-42".into(),
            misc: "Ask finance first.\nSecond line.".into(),
            summary_instructions: "One sentence, start with the number.".into(),
            dirs: vec![
                ProjectDir { path: "/code/billing".into(), origin: "git@x:billing.git".into() },
                ProjectDir { path: "/code/billing docs".into(), origin: String::new() },
            ],
            ..Project::default()
        }
    }

    fn vault_dir() -> tempfile::TempDir {
        tempfile::tempdir().unwrap()
    }

    /// Everything about a project except the ids that differ between indexes.
    fn comparable(mut p: Project) -> Project {
        p.id = 0;
        p.vault_id = None;
        p
    }

    #[test]
    fn note_round_trips_including_headings_inside_text() {
        let note = render_note(&sample(), Some("kkbae"));
        assert!(note.starts_with("# Project: Billing API\n"), "{note}");
        let parsed = parse_note(&note).unwrap();
        assert_eq!(parsed.vault_name.as_deref(), Some("kkbae"));
        assert_eq!(parsed.project, sample());
        assert_eq!(render_note(&parsed.project, Some("kkbae")), note, "rendering is stable");
    }

    #[test]
    fn a_note_without_a_project_title_is_an_error() {
        assert!(parse_note("just some text").is_err());
    }

    #[test]
    fn file_names_are_safe() {
        assert_eq!(note_file_name("Billing API"), "Billing API.md");
        assert_eq!(note_file_name("a/b:c"), "a-b-c.md");
    }

    #[test]
    fn export_then_import_restores_after_losing_the_index() {
        let dir = vault_dir();
        let path = dir.path().to_string_lossy().into_owned();
        let mut store = Store::open_in_memory().unwrap();
        let vault = store.add_vault("kkbae", &path, "").unwrap();
        let mut p = sample();
        p.vault_id = Some(vault.id);
        store.add_project(&p).unwrap();

        let report = export(&store, &[vault.clone()]).unwrap();
        assert_eq!(report.written.len(), 1);
        let file = dir.path().join(NOTES_DIR).join("Billing API.md");
        let first = std::fs::read_to_string(&file).unwrap();
        export(&store, &[vault]).unwrap();
        assert_eq!(std::fs::read_to_string(&file).unwrap(), first, "a second export changes nothing");

        let mut fresh = Store::open_in_memory().unwrap();
        let vault = fresh.add_vault("kkbae", &path, "").unwrap();
        let report = import(&mut fresh, &[vault.clone()], false).unwrap();
        assert_eq!(report.added, ["Billing API"]);
        let restored = fresh.list_projects().unwrap();
        assert_eq!(restored.len(), 1);
        assert_eq!(restored[0].vault_id, Some(vault.id));
        assert_eq!(comparable(restored[0].clone()), sample());
    }

    #[test]
    fn export_skips_projects_without_a_vault() {
        let dir = vault_dir();
        let mut store = Store::open_in_memory().unwrap();
        let vault = store.add_vault("v", &dir.path().to_string_lossy(), "").unwrap();
        store.add_project(&sample()).unwrap();
        let report = export(&store, &[vault]).unwrap();
        assert!(report.written.is_empty());
        assert_eq!(report.skipped, ["Billing API"]);
        assert!(!dir.path().join(NOTES_DIR).exists());
    }

    #[test]
    fn import_skips_existing_names_unless_overwrite() {
        let dir = vault_dir();
        let mut store = Store::open_in_memory().unwrap();
        let vault = store.add_vault("v", &dir.path().to_string_lossy(), "").unwrap();
        let mut p = sample();
        p.vault_id = Some(vault.id);
        let saved = store.add_project(&p).unwrap();
        export(&store, &[vault.clone()]).unwrap();

        let mut changed = saved.clone();
        changed.description = "edited in the index".into();
        store.update_project(&changed).unwrap();

        let report = import(&mut store, &[vault.clone()], false).unwrap();
        assert_eq!(report.skipped, ["Billing API"]);
        assert_eq!(store.find_project("Billing API").unwrap().unwrap().description, "edited in the index");

        let report = import(&mut store, &[vault], true).unwrap();
        assert_eq!(report.updated, ["Billing API"]);
        assert_eq!(store.find_project("Billing API").unwrap().unwrap().description, sample().description);
    }

    #[test]
    fn import_with_an_unknown_vault_keeps_the_project_unlinked_and_warns() {
        let dir = vault_dir();
        let mut store = Store::open_in_memory().unwrap();
        let vault = store.add_vault("v", &dir.path().to_string_lossy(), "").unwrap();
        std::fs::create_dir_all(dir.path().join(NOTES_DIR)).unwrap();
        std::fs::write(dir.path().join(NOTES_DIR).join("Billing API.md"), render_note(&sample(), Some("ghost"))).unwrap();

        let report = import(&mut store, &[vault], false).unwrap();
        assert_eq!(report.added, ["Billing API"]);
        assert!(report.warnings.iter().any(|w| w.contains("ghost")), "{:?}", report.warnings);
        assert_eq!(store.find_project("Billing API").unwrap().unwrap().vault_id, None);
    }

    #[test]
    fn import_reports_unreadable_notes_and_directory_clashes_without_stopping() {
        let dir = vault_dir();
        let mut store = Store::open_in_memory().unwrap();
        let vault = store.add_vault("v", &dir.path().to_string_lossy(), "").unwrap();
        let mut other = sample();
        other.name = "Other".into();
        store.add_project(&other).unwrap(); // already owns /code/billing
        let notes = dir.path().join(NOTES_DIR);
        std::fs::create_dir_all(&notes).unwrap();
        std::fs::write(notes.join("Billing API.md"), render_note(&sample(), Some("v"))).unwrap();
        std::fs::write(notes.join("junk.md"), "not a project note").unwrap();

        let report = import(&mut store, &[vault], false).unwrap();
        assert!(report.added.is_empty());
        assert!(report.warnings.iter().any(|w| w.contains("junk.md")), "{:?}", report.warnings);
        assert!(report.warnings.iter().any(|w| w.contains("Billing API") && w.contains("/code/billing")), "{:?}", report.warnings);
    }
}
